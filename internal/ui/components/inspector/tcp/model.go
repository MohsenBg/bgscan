package tcp

import (
	"strconv"
	"time"

	"github.com/MohsenBg/bgscan/internal/core/config"
	"github.com/MohsenBg/bgscan/internal/core/config/validate"
	"github.com/MohsenBg/bgscan/internal/ui/components/basic/input"
	"github.com/MohsenBg/bgscan/internal/ui/components/basic/input/textinput"
	"github.com/MohsenBg/bgscan/internal/ui/components/basic/inspector"
	"github.com/MohsenBg/bgscan/internal/ui/components/basic/notice"
	"github.com/MohsenBg/bgscan/internal/ui/shared/ui"

	tea "charm.land/bubbletea/v2"
)

const groupTCP = "TCP Settings"

const (
	descWorkers      = "The number of concurrent workers performing TCP connection attempts. Higher values increase scan speed at the cost of greater CPU and network utilization."
	descPort         = "The target TCP port to probe on each IP address. The scanner attempts to establish a TCP connection to this port."
	descTimeout      = "Maximum duration in milliseconds to wait for a TCP connection to be established. Targets failing to respond within this window are considered unreachable."
	descTries        = "The maximum number of retry attempts per target to mitigate connection failures. Higher values improve reliability but increase total scan duration."
	descOutputPrefix = "The filename prefix applied to all output files generated by this module, allowing easy identification when running multiple scans."
)

type Model struct {
	session   *ui.Session
	name      string
	id        ui.ComponentID
	inspector ui.Component
}

func (m *Model) ID() ui.ComponentID { return m.id }
func (m *Model) Init() tea.Cmd      { return nil }
func (m *Model) Mode() ui.KeyMode   { return ui.KeyModeNormal }
func (m *Model) Name() string       { return m.name }
func (m *Model) OnClose() tea.Cmd   { return nil }

func saveTCP(session *ui.Session) tea.Cmd {
	if err := session.Store.SaveTCP(session.Config.TCP); err != nil {
		session.Env().Log.Error("Failed to save TCP settings: %v", err)
		return notice.NewNoticeCmd(session.Env(), "Failed to save TCP settings", err.Error(), notice.NOTICE_ERROR)
	}
	return nil
}

func intInput(session *ui.Session, title string, value int, validate func(string) error, set func(int)) input.Input[string] {
	return textinput.New(session.Env(), title,
		textinput.WithValue(strconv.Itoa(value)),
		textinput.WithValidation(validate),
		textinput.WithFocus(),
		textinput.WithOnSubmit(func(v string) tea.Cmd {
			n, err := strconv.Atoi(v)
			if err != nil {
				return notice.NewNoticeCmd(session.Env(), "Invalid "+title, err.Error(), notice.NOTICE_ERROR)
			}
			set(n)
			return saveTCP(session)
		}),
	)
}

func durationMSInput(session *ui.Session, title string, value time.Duration, validate func(string) error, set func(time.Duration)) input.Input[string] {
	return textinput.New(session.Env(), title,
		textinput.WithValue(strconv.FormatInt(value.Milliseconds(), 10)),
		textinput.WithValidation(validate),
		textinput.WithFocus(),
		textinput.WithOnSubmit(func(v string) tea.Cmd {
			n, err := strconv.Atoi(v)
			if err != nil {
				return notice.NewNoticeCmd(session.Env(), "Invalid "+title, err.Error(), notice.NOTICE_ERROR)
			}
			set(time.Duration(n) * time.Millisecond)
			return saveTCP(session)
		}),
	)
}

func stringInput(session *ui.Session, title, value string, validate func(string) error, set func(string)) input.Input[string] {
	return textinput.New(session.Env(), title,
		textinput.WithValue(value),
		textinput.WithValidation(validate),
		textinput.WithFocus(),
		textinput.WithOnSubmit(func(v string) tea.Cmd {
			set(v)
			return saveTCP(session)
		}),
	)
}

func New(session *ui.Session, name string) *Model {
	cfg := &session.Config.TCP

	workers := intInput(session, "Enter number of workers", cfg.Workers,
		func(v string) error {
			n, err := strconv.Atoi(v)
			if err != nil {
				return err
			}
			tmp := *cfg
			tmp.Workers = n
			return fieldErr(validate.ValidateTCP(tmp), validate.FieldWorkers)
		},
		func(n int) { cfg.Workers = n })

	port := intInput(session, "Enter TCP port", cfg.Port,
		func(v string) error {
			n, err := strconv.Atoi(v)
			if err != nil {
				return err
			}
			tmp := *cfg
			tmp.Port = n
			return fieldErr(validate.ValidateTCP(tmp), validate.FieldPort)
		},
		func(n int) { cfg.Port = n })

	timeout := durationMSInput(session, "Enter timeout (milliseconds)", cfg.Timeout.Duration(),
		func(v string) error {
			n, err := strconv.Atoi(v)
			if err != nil {
				return err
			}
			tmp := *cfg
			tmp.Timeout = config.NewDurationMS(time.Duration(n) * time.Millisecond)
			return fieldErr(validate.ValidateTCP(tmp), validate.FieldTimeout)
		},
		func(d time.Duration) { cfg.Timeout = config.NewDurationMS(d) })

	tries := intInput(session, "Enter maximum attempts", int(cfg.Tries),
		func(v string) error {
			n, err := strconv.ParseUint(v, 10, 16)
			if err != nil {
				return err
			}
			tmp := *cfg
			tmp.Tries = uint16(n)
			return fieldErr(validate.ValidateTCP(tmp), validate.FieldTries)
		},
		func(n int) { cfg.Tries = uint16(n) })

	prefixOutput := stringInput(session, "Enter output file prefix", cfg.OutputPrefix,
		func(v string) error {
			tmp := *cfg
			tmp.OutputPrefix = v
			return fieldErr(validate.ValidateTCP(tmp), validate.FieldOutputPrefix)
		},
		func(v string) { cfg.OutputPrefix = v })

	fields := []inspector.Field{
		{Name: "Workers", Description: descWorkers, Group: groupTCP, Input: inspector.Adapt(workers), Visible: alwaysVisible, Format: inspector.FormatInt},
		{Name: "Port", Description: descPort, Group: groupTCP, Input: inspector.Adapt(port), Visible: alwaysVisible},
		{Name: "Timeout", Description: descTimeout, Group: groupTCP, Input: inspector.Adapt(timeout), Visible: alwaysVisible, Format: inspector.FormatDurationMS},
		{Name: "Tries", Description: descTries, Group: groupTCP, Input: inspector.Adapt(tries), Visible: alwaysVisible, Format: inspector.FormatInt},
		{Name: "Prefix Output", Description: descOutputPrefix, Group: groupTCP, Input: inspector.Adapt(prefixOutput), Visible: alwaysVisible},
	}

	return &Model{
		session:   session,
		name:      name,
		id:        ui.NewComponentID(),
		inspector: inspector.New(session.Env(), "tcp settings", fields),
	}
}

func alwaysVisible() bool { return true }

func fieldErr(errs map[validate.Field]error, field validate.Field) error {
	return errs[field]
}
