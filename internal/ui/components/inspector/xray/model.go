package xray

import (
	"strconv"
	"time"

	"github.com/MohsenBg/bgscan/internal/core/config"
	"github.com/MohsenBg/bgscan/internal/core/config/validate"
	"github.com/MohsenBg/bgscan/internal/ui/components/basic/input"
	"github.com/MohsenBg/bgscan/internal/ui/components/basic/input/selectinput"
	"github.com/MohsenBg/bgscan/internal/ui/components/basic/input/textinput"
	"github.com/MohsenBg/bgscan/internal/ui/components/basic/inspector"
	"github.com/MohsenBg/bgscan/internal/ui/components/basic/notice"
	"github.com/MohsenBg/bgscan/internal/ui/shared/ui"

	tea "charm.land/bubbletea/v2"
	"charm.land/huh/v2"
)

const groupXray = "Xray Settings"

const (
	descWorkers              = "The number of concurrent workers performing Xray connectivity tests. Higher values increase test throughput at the cost of greater bandwidth and CPU utilization."
	descConnectivityTestType = "The type of connectivity test to perform: 0 (Connectivity only), 1 (Download only), 2 (Upload only), or 3 (Both)."
	descDownloadSpeed        = "Target download speed (in kbps) to test against within the configured speed test timeout. Used when connectivity test type includes download."
	descUploadSpeed          = "Target upload speed (in kbps) to test against within the configured speed test timeout. Used when connectivity test type includes upload."
	descTimeout              = "Maximum duration in milliseconds to wait for the latency test. Tests failing to respond within this window are considered failed."
	descSpeedTestTimeout     = "Maximum duration in milliseconds to wait for the download/upload speed test. Also determines bytes requested: timeout_s * speed_kbps * 1000 / 8."
	descOutputPrefix         = "The filename prefix applied to all output files generated by this module, allowing easy identification when running multiple scans."
	descPreScanType          = "The pre-scan connectivity test to perform before running Xray: 'none' (skip), 'icmp', 'tcp', or 'http'."
	descMaxConcurrentDials   = "Maximum concurrent outbound dials process-wide. Caps sockets and memory during scans. Set to 0 for unlimited."
	descDialMaxAttempts      = "Dial attempts per outbound dispatch before giving up on a target."
)

type Model struct {
	session   *ui.Session
	name      string
	id        ui.ComponentID
	inspector ui.Component
}

func (m *Model) ID() ui.ComponentID { return m.id }
func (m *Model) Init() tea.Cmd      { return nil }
func (m *Model) Mode() ui.KeyMode   { return ui.KeyModeNormal }
func (m *Model) Name() string       { return m.name }
func (m *Model) OnClose() tea.Cmd   { return nil }

func saveXray(session *ui.Session) tea.Cmd {
	if err := session.Store.SaveXray(session.Config.Xray); err != nil {
		session.Env().Log.Error("Failed to save Xray settings: %v", err)
		return notice.NewNoticeCmd(session.Env(), "Failed to save Xray settings", err.Error(), notice.NOTICE_ERROR)
	}
	return nil
}

func intInput(session *ui.Session, title string, value int, val func(string) error, set func(int)) input.Input[string] {
	return textinput.New(session.Env(), title,
		textinput.WithValue(strconv.Itoa(value)),
		textinput.WithValidation(val),
		textinput.WithFocus(),
		textinput.WithOnSubmit(func(v string) tea.Cmd {
			n, err := strconv.Atoi(v)
			if err != nil {
				return notice.NewNoticeCmd(session.Env(), "Invalid "+title, err.Error(), notice.NOTICE_ERROR)
			}
			set(n)
			return saveXray(session)
		}),
	)
}

func durationMSInput(session *ui.Session, title string, value time.Duration, val func(string) error, set func(time.Duration)) input.Input[string] {
	return textinput.New(session.Env(), title,
		textinput.WithValue(strconv.FormatInt(value.Milliseconds(), 10)),
		textinput.WithValidation(val),
		textinput.WithFocus(),
		textinput.WithOnSubmit(func(v string) tea.Cmd {
			n, err := strconv.Atoi(v)
			if err != nil {
				return notice.NewNoticeCmd(session.Env(), "Invalid "+title, err.Error(), notice.NOTICE_ERROR)
			}
			set(time.Duration(n) * time.Millisecond)
			return saveXray(session)
		}),
	)
}

func stringInput(session *ui.Session, title, value string, val func(string) error, set func(string)) input.Input[string] {
	return textinput.New(session.Env(), title,
		textinput.WithValue(value),
		textinput.WithValidation(val),
		textinput.WithFocus(),
		textinput.WithOnSubmit(func(v string) tea.Cmd {
			set(v)
			return saveXray(session)
		}),
	)
}

func New(session *ui.Session, name string) *Model {
	cfg := &session.Config.Xray

	workers := intInput(session, "Enter number of workers", cfg.Workers,
		func(v string) error {
			n, err := strconv.Atoi(v)
			if err != nil {
				return err
			}
			tmp := *cfg
			tmp.Workers = n
			return fieldErr(validate.ValidateXray(tmp), validate.FieldWorkers)
		},
		func(n int) { cfg.Workers = n })

	connectivityTestType := selectinput.New(session.Env(), "Select connectivity test type",
		selectinput.WithValue(cfg.ConnectivityTestType),
		selectinput.WithFocus[config.ConnectivityTest](),
		selectinput.WithOptions(
			huh.NewOption("Connectivity Only", config.ConnectivityOnly),
			huh.NewOption("Download Speed Only", config.DownloadSpeedOnly),
			huh.NewOption("Upload Speed Only", config.UploadSpeedOnly),
			huh.NewOption("Both", config.Both),
		),
		selectinput.WithOnSubmit(func(v config.ConnectivityTest) tea.Cmd {
			cfg.ConnectivityTestType = v
			return saveXray(session)
		}),
	)

	includesDownload := func() bool {
		return cfg.ConnectivityTestType == config.DownloadSpeedOnly || cfg.ConnectivityTestType == config.Both
	}
	includesUpload := func() bool {
		return cfg.ConnectivityTestType == config.UploadSpeedOnly || cfg.ConnectivityTestType == config.Both
	}

	downloadSpeed := intInput(session, "Enter download speed (kbps)", cfg.DownloadSpeed,
		func(v string) error {
			n, err := strconv.Atoi(v)
			if err != nil {
				return err
			}
			tmp := *cfg
			tmp.DownloadSpeed = n
			return fieldErr(validate.ValidateXray(tmp), validate.FieldDownloadSpeed)
		},
		func(n int) { cfg.DownloadSpeed = n })

	uploadSpeed := intInput(session, "Enter upload speed (kbps)", cfg.UploadSpeed,
		func(v string) error {
			n, err := strconv.Atoi(v)
			if err != nil {
				return err
			}
			tmp := *cfg
			tmp.UploadSpeed = n
			return fieldErr(validate.ValidateXray(tmp), validate.FieldUploadSpeed)
		},
		func(n int) { cfg.UploadSpeed = n })

	timeout := durationMSInput(session, "Enter latency timeout (milliseconds)", cfg.Timeout.Duration(),
		func(v string) error {
			n, err := strconv.Atoi(v)
			if err != nil {
				return err
			}
			tmp := *cfg
			tmp.Timeout = config.NewDurationMS(time.Duration(n) * time.Millisecond)
			return fieldErr(validate.ValidateXray(tmp), validate.FieldTimeout)
		},
		func(d time.Duration) { cfg.Timeout = config.NewDurationMS(d) })

	speedTestTimeout := durationMSInput(session, "Enter speed test timeout (milliseconds)", cfg.SpeedTestTimeout.Duration(),
		func(v string) error {
			n, err := strconv.Atoi(v)
			if err != nil {
				return err
			}
			tmp := *cfg
			tmp.SpeedTestTimeout = config.NewDurationMS(time.Duration(n) * time.Millisecond)
			return fieldErr(validate.ValidateXray(tmp), validate.FieldSpeedTestTimeout)
		},
		func(d time.Duration) { cfg.SpeedTestTimeout = config.NewDurationMS(d) })

	preScanType := selectinput.New(session.Env(), "Select pre-scan type",
		selectinput.WithValue(cfg.PreScanType),
		selectinput.WithFocus[string](),
		selectinput.WithOptions(
			huh.NewOption("None", "none"),
			huh.NewOption("ICMP", "icmp"),
			huh.NewOption("TCP", "tcp"),
			huh.NewOption("HTTP", "http"),
		),
		selectinput.WithOnSubmit(func(v string) tea.Cmd {
			cfg.PreScanType = v
			return saveXray(session)
		}),
	)

	prefixOutput := stringInput(session, "Enter output file prefix", cfg.OutputPrefix,
		func(v string) error {
			tmp := *cfg
			tmp.OutputPrefix = v
			return fieldErr(validate.ValidateXray(tmp), validate.FieldOutputPrefix)
		},
		func(v string) { cfg.OutputPrefix = v })

	maxConcurrentDials := intInput(session, "Enter max concurrent dials (0 = unlimited)", cfg.MaxConcurrentDials,
		func(v string) error {
			n, err := strconv.Atoi(v)
			if err != nil {
				return err
			}
			tmp := *cfg
			tmp.MaxConcurrentDials = n
			return fieldErr(validate.ValidateXray(tmp), validate.FieldMaxConcurrentDials)
		},
		func(n int) { cfg.MaxConcurrentDials = n })

	dialMaxAttempts := intInput(session, "Enter dial max attempts", cfg.DialMaxAttempts,
		func(v string) error {
			n, err := strconv.Atoi(v)
			if err != nil {
				return err
			}
			tmp := *cfg
			tmp.DialMaxAttempts = n
			return fieldErr(validate.ValidateXray(tmp), validate.FieldDialMaxAttempts)
		},
		func(n int) { cfg.DialMaxAttempts = n })

	fields := []inspector.Field{
		{Name: "Workers", Description: descWorkers, Group: groupXray, Input: inspector.Adapt(workers), Visible: alwaysVisible, Format: inspector.FormatInt},
		{Name: "Connectivity Test Type", Description: descConnectivityTestType, Group: groupXray, Input: inspector.Adapt(connectivityTestType), Visible: alwaysVisible},
		{Name: "Download Speed", Description: descDownloadSpeed, Group: groupXray, Input: inspector.Adapt(downloadSpeed), Visible: includesDownload, Format: inspector.FormatDataSpeed},
		{Name: "Upload Speed", Description: descUploadSpeed, Group: groupXray, Input: inspector.Adapt(uploadSpeed), Visible: includesUpload, Format: inspector.FormatDataSpeed},
		{Name: "Timeout", Description: descTimeout, Group: groupXray, Input: inspector.Adapt(timeout), Visible: alwaysVisible, Format: inspector.FormatDurationMS},
		{Name: "Speed Test Timeout", Description: descSpeedTestTimeout, Group: groupXray, Input: inspector.Adapt(speedTestTimeout), Visible: alwaysVisible, Format: inspector.FormatDurationMS},
		{Name: "Pre-Scan Type", Description: descPreScanType, Group: groupXray, Input: inspector.Adapt(preScanType), Visible: alwaysVisible},
		{Name: "Prefix Output", Description: descOutputPrefix, Group: groupXray, Input: inspector.Adapt(prefixOutput), Visible: alwaysVisible},
		{Name: "Max Concurrent Dials", Description: descMaxConcurrentDials, Group: groupXray, Input: inspector.Adapt(maxConcurrentDials), Visible: alwaysVisible, Format: inspector.FormatIntOrUnlimited},
		{Name: "Dial Max Attempts", Description: descDialMaxAttempts, Group: groupXray, Input: inspector.Adapt(dialMaxAttempts), Visible: alwaysVisible, Format: inspector.FormatInt},
	}

	return &Model{
		session:   session,
		name:      name,
		id:        ui.NewComponentID(),
		inspector: inspector.New(session.Env(), "xray settings", fields),
	}
}

func alwaysVisible() bool { return true }

func fieldErr(errs map[validate.Field]error, field validate.Field) error {
	return errs[field]
}
